def text_width(text: str, font: dict[str, tuple[str, ...]], scale: int = 1,
               spacing: int = 1) -> int:
    if not text:
        return 0
    glyph_w = len(next(iter(font.values()))[0])
    return len(text) * glyph_w * scale + (len(text) - 1) * spacing * scale


def draw_text(canvas, x: int, y: int, text: str, color: int,
              font: dict[str, tuple[str, ...]] = FONT_5x7, scale: int = 1,
              spacing: int = 1, align: str = "left") -> int:
    """Draw bitmap text into a PixelCanvas. Returns the x after the text."""
    w = text_width(text, font, scale, spacing)
    if align == "center":
        x -= w // 2
    elif align == "right":
        x -= w
    glyph_w, glyph_h = len(next(iter(font.values()))[0]), len(next(iter(font.values())))
    cx = x
    for ch in text.upper():
        glyph = font.get(ch, font.get("?", FONT_5x7["?"]))
        for gy, row in enumerate(glyph):
            for gx, bit in enumerate(row):
                if bit == "1":
                    canvas.rect(cx + gx * scale, y + gy * scale,
                                scale, scale, color)
        cx += (glyph_w + spacing) * scale
    return cx


def text_cells(text: str, font: dict[str, tuple[str, ...]] = FONT_5x7,
               scale: int = 1, spacing: int = 1) -> int:
    """Approximate terminal cell width of bitmap text (1 pixel = 1 column)."""
    return text_width(text, font, scale, spacing)
